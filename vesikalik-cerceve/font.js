export const ADVANCE = 6;   // 4 birim harf + 2 birim aralık
export const SPACE = 4;

// Metni desteklenen karakterlere indirger (Türkçe büyük harf kuralıyla).
export function normalizeText(s) {
  return String(s || '')
    .replace(/<3/g, '♥')
    .toLocaleUpperCase('tr-TR')
    .split('')
    .filter((ch) => ch === ' ' || GLYPHS[ch])
    .join('')
    .replace(/\s+/g, ' ')
    .trim();
}

// Satırı birim koordinatlarda segment listesine çevirir; genişliği de döndürür.
export function layoutLine(text) {
  const segs = [];
  let x = 0;
  for (const ch of text) {
    if (ch === ' ') { x += SPACE; continue; }
    for (const line of GLYPHS[ch]) {
      for (let i = 0; i < line.length - 1; i++) {
        segs.push([[line[i][0] + x, line[i][1]], [line[i + 1][0] + x, line[i + 1][1]]]);
      }
    }
    x += ADVANCE;
  }
  const width = text.length ? x - (text.endsWith(' ') ? SPACE : ADVANCE - 4) : 0;
  return { segs, width };
}
